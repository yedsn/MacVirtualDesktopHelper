import Foundation

enum Localization {
 static var language = "zh-CN"
 static var isEnglish: Bool { language == "en" }

 static func text(_ source: String) -> String {
  isEnglish ? (english[source] ?? source) : source
 }

 static func format(_ source: String, _ arguments: CVarArg...) -> String {
  String(format: text(source), arguments: arguments)
 }

 static func loadPersistedLanguage() {
  guard let support = try? FileManager.default.url(for: .applicationSupportDirectory, in: .userDomainMask, appropriateFor: nil, create: false) else { return }
  let url = support.appendingPathComponent("MacVirtualDesktopHelper/desktop-rule-state.json")
  guard let data = try? Data(contentsOf: url),
   let state = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any],
   let settings = state["settings"] as? [String: Any] else { return }
  language = settings["language"] as? String == "en" ? "en" : "zh-CN"
 }

